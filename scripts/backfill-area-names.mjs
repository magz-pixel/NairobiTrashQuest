#!/usr/bin/env node
/**
 * Generate SQL that gives old reports a real place name instead of "Nairobi" / blank.
 *
 * Reads public reports with the anon key (read-only), reverse-geocodes each one with the
 * same picking rule the app now uses (src/lib/wards.ts → pickAreaName), and writes
 * UPDATE statements to a .sql file. It does NOT write to the database: review the file,
 * then run it in the Supabase SQL editor.
 *
 *   node scripts/backfill-area-names.mjs [outfile]
 *
 * Needs VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY in .env.local or the environment.
 */
import fs from 'node:fs'

for (const file of ['.env.local', '.env']) {
  if (!fs.existsSync(file)) continue
  for (const line of fs.readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = line.match(/^\s*([A-Z0-9_]+)\s*=\s*(.*)\s*$/)
    if (m && !process.env[m[1]]) process.env[m[1]] = m[2]
  }
}
const url = process.env.VITE_SUPABASE_URL
const key = process.env.VITE_SUPABASE_ANON_KEY
if (!url || !key) {
  console.error('Set VITE_SUPABASE_URL and VITE_SUPABASE_ANON_KEY (e.g. in .env.local).')
  process.exit(1)
}
const outFile = process.argv[2] ?? `supabase/backfills/${new Date().toISOString().slice(0, 10)}_area_names.sql`

const GENERIC = /^(kenya|uganda|tanzania|nairobi|nairobi city|kampala|dar es salaam)$/i
const clean = (n) => n.replace(/\s+(ward|sub-?location|location|sub-?county|constituency|division)$/i, '').trim()

/** Keep in sync with pickAreaName in src/lib/wards.ts. */
function pickAreaName(d) {
  const admin = (d.localityInfo?.administrative ?? [])
    .filter((a) => a.name)
    .sort((a, b) => (a.order ?? a.adminLevel ?? 0) - (b.order ?? b.adminLevel ?? 0))
  const ward = admin.find((a) => /\bward$/i.test(a.name))
  if (ward) return clean(ward.name)
  const specific = admin.map((a) => clean(a.name)).filter((n) => n && !GENERIC.test(n))
  if (specific.length) return specific[specific.length - 1]
  return null
}

const res = await fetch(`${url}/rest/v1/reports?select=id,latitude,longitude,area_name,city`, {
  headers: { apikey: key, Authorization: `Bearer ${key}` },
})
if (!res.ok) throw new Error(`Supabase read failed: ${res.status} ${await res.text()}`)
const rows = (await res.json()).filter((r) => !r.area_name || GENERIC.test(r.area_name.trim()))
console.log(`${rows.length} reports need a place name`)

const sql = [
  '-- Backfill reports.area_name from reverse geocoding (generated by scripts/backfill-area-names.mjs).',
  '-- Only touches rows whose name is still blank or just the city name.',
  'begin;',
]
for (const r of rows) {
  const geo = new URL('https://api.bigdatacloud.net/data/reverse-geocode-client')
  geo.searchParams.set('latitude', String(r.latitude))
  geo.searchParams.set('longitude', String(r.longitude))
  geo.searchParams.set('localityLanguage', 'en')
  const name = pickAreaName(await (await fetch(geo, { signal: AbortSignal.timeout(10000) })).json())
  console.log(`${r.id}  ${r.latitude.toFixed(4)},${r.longitude.toFixed(4)}  →  ${name ?? '(no better name)'}`)
  if (!name) continue
  const lit = `'${name.replace(/'/g, "''")}'`
  sql.push(
    `update public.reports set area_name = ${lit} where id = '${r.id}' and (area_name is null or area_name ~* '^(kenya|uganda|tanzania|nairobi|nairobi city|kampala|dar es salaam)$');`,
  )
  await new Promise((ok) => setTimeout(ok, 300))
}
sql.push('commit;', '')
fs.mkdirSync(outFile.replace(/[\\/][^\\/]+$/, ''), { recursive: true })
fs.writeFileSync(outFile, sql.join('\n'))
console.log(`Wrote ${sql.filter((l) => l.startsWith('update ')).length} updates to ${outFile}`)
